import { chromium } from '@playwright/test';
import ExcelJS from 'exceljs';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
try {
 const page=await browser.newPage();
 page.setDefaultTimeout(120000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3000/admin',{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'Importar dados',exact:true}).click();
 const book=new ExcelJS.Workbook();const sheet=book.addWorksheet('Calendário');
 sheet.addRow(['date','event_type','title','grade','class','subject']);
 sheet.addRow([new Date('2027-03-02T12:00:00Z'),'assessment','Teste de prévia XLSX','7','7A','MAT']);
 const buffer=await book.xlsx.writeBuffer();
 await page.getByLabel('Arquivo para importar').setInputFiles({name:'teste.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:Buffer.from(buffer)});
 await page.getByRole('heading',{name:'Prévia: teste.xlsx'}).waitFor();
 assert.match(await page.locator('.import-preview pre').innerText(),/Teste de prévia XLSX/);
 const response=await page.request.get('http://localhost:3000/api/school');const {data}=await response.json();
 await page.getByLabel('O que deseja importar?').selectOption('backup');
 await page.getByLabel('Arquivo para importar').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(data))});
 await page.getByRole('heading',{name:'Prévia: backup.json'}).waitFor();
 assert.match(await page.locator('.import-preview pre').innerText(),/schoolName/);
 await page.goto('http://localhost:3000/student',{waitUntil:'networkidle'});
 await page.getByRole('button',{name:/7º ano/}).click();
 await page.getByRole('button',{name:'Turma A',exact:true}).click();
 await page.getByLabel('Seu nome',{exact:true}).fill('Aluno de demonstração');
 await page.getByRole('button',{name:'Continuar',exact:true}).click();
 await page.getByRole('button',{name:'Definir horários',exact:true}).click();
 const first=page.getByRole('button',{name:'Seg 15:00 às 15:30',exact:true});
 const last=page.getByRole('button',{name:'Seg 16:00 às 16:30',exact:true});
 const a=await first.boundingBox(),b=await last.boundingBox();
 await page.mouse.move(a.x+a.width/2,a.y+a.height/2);await page.mouse.down();
 await page.mouse.move(b.x+b.width/2,b.y+b.height/2,{steps:15});await page.mouse.up();
 assert.equal(await page.locator('.time-slot[aria-pressed="true"]').count(),3);
 const next=page.getByRole('button',{name:'Ter 15:00 às 15:30',exact:true});
 await next.focus();await page.keyboard.press('Space');assert.equal(await next.getAttribute('aria-pressed'),'true');
 await page.getByRole('button',{name:/Como funciona/}).click();
 await page.keyboard.press('Escape');assert.equal(await page.getByRole('dialog').count(),0);
 assert.deepEqual(errors,[]);
 console.log('PASS: XLSX preview, JSON backup preview, mouse drag, keyboard selection, accessible dialog. No changes saved.');
} finally {await browser.close()}
